_STATUS_CLS = {"open": "blue", "active": "green", "closed": "slate", "archived": "slate"}
_PRIORITY_CLS = {"critical": "red", "high": "amber", "medium": "blue", "low": "slate"}


def _fmt_dt(value) -> str:
    if not value:
        return "n/a"
    if isinstance(value, str):
        return value[:19].replace("T", " ")
    return value.strftime("%Y-%m-%d %H:%M")


def _conf_bar(confidence) -> str:
    try:
        pct = int(float(confidence) * 100)
    except (TypeError, ValueError):
        pct = 0
    fill = max(0, min(100, pct))
    return (
        f'<span class="confidence-bar-bg">'
        f'<span class="confidence-bar-fill" style="width:{fill}%"></span>'
        f'</span> <span style="font-size:11px;color:#64748b">{pct}%</span>'
    )


def _scans_table(scans: list) -> str:
    if not scans:
        return "<p style='color:#94a3b8'>No scans have been run for this case.</p>"
    rows = ""
    for s in scans:
        status_cls = {"completed": "green", "partial": "amber", "failed": "red"}.get(s.get("status", ""), "slate")
        rows += (
            f"<tr>"
            f"<td>{s.get('seed_value','')}</td>"
            f"<td><span class='badge badge-blue'>{s.get('seed_kind','')}</span></td>"
            f"<td><span class='badge badge-{status_cls}'>{s.get('status','')}</span></td>"
            f"<td>{s.get('progress',0)}/{s.get('total_modules',0)}</td>"
            f"<td style='color:#94a3b8;font-size:11px'>{_fmt_dt(s.get('created_at'))}</td>"
            f"</tr>"
        )
    return (
        "<table><thead><tr>"
        "<th>Target</th><th>Kind</th><th>Status</th><th>Modules</th><th>Started</th>"
        "</tr></thead><tbody>" + rows + "</tbody></table>"
    )


def _indicators_table(indicators: list, report_type: str) -> str:
    if report_type not in {"technical", "full", "summary"}:
        return ""
    if not indicators:
        return "<h2>Indicators</h2><p style='color:#94a3b8'>No indicators found.</p>"
    rows = ""
    for ind in indicators[:50]:
        kind_cls = {
            "domain": "blue", "ip": "green", "email": "amber",
            "hostname": "slate", "url": "slate",
        }.get(ind.get("kind", ""), "slate")
        rows += (
            f"<tr>"
            f"<td><span class='badge badge-{kind_cls}'>{ind.get('kind','')}</span></td>"
            f"<td style='font-family:monospace'>{ind.get('value','')}</td>"
            f"<td>{_conf_bar(ind.get('confidence', 0))}</td>"
            f"<td style='color:#94a3b8;font-size:11px'>{ind.get('source_module','')}</td>"
            f"</tr>"
        )
    return (
        "<h2>Indicators</h2>"
        "<table><thead><tr>"
        "<th>Kind</th><th>Value</th><th>Confidence</th><th>Source</th>"
        "</tr></thead><tbody>" + rows + "</tbody></table>"
    )


def _relationships_table(edges: list, indicator_map: dict, report_type: str) -> str:
    if report_type not in {"technical", "full"}:
        return ""
    if not edges:
        return "<h2>Relationships</h2><p style='color:#94a3b8'>No relationships found.</p>"
    rows = ""
    for e in edges[:50]:
        src = indicator_map.get(str(e.get("src_id", "")), {})
        dst = indicator_map.get(str(e.get("dst_id", "")), {})
        rows += (
            f"<tr>"
            f"<td style='font-family:monospace'>{src.get('value', str(e.get('src_id','')))}</td>"
            f"<td style='color:#3b82f6;font-weight:600'>{e.get('relationship_type','')}</td>"
            f"<td style='font-family:monospace'>{dst.get('value', str(e.get('dst_id','')))}</td>"
            f"<td style='color:#94a3b8;font-size:11px'>{e.get('source_module','')}</td>"
            f"<td>{_conf_bar(e.get('confidence', 0))}</td>"
            f"</tr>"
        )
    return (
        "<h2>Relationships</h2>"
        "<table><thead><tr>"
        "<th>Source</th><th>Relationship</th><th>Target</th><th>Module</th><th>Confidence</th>"
        "</tr></thead><tbody>" + rows + "</tbody></table>"
    )


def _timeline_block(case_data: dict, scans: list, report_type: str) -> str:
    if report_type not in {"timeline", "full"}:
        return ""
    events = [{"time": case_data.get("created_at", ""), "label": "Case created", "detail": case_data.get("title", "")}]
    for s in scans:
        events.append({"time": s.get("created_at", ""), "label": f"Scan started: {s.get('seed_value','')}", "detail": s.get("seed_kind", "")})
        if s.get("finished_at"):
            events.append({"time": s.get("finished_at", ""), "label": f"Scan {s.get('status','done')}: {s.get('seed_value','')}", "detail": ""})
    events.sort(key=lambda e: e.get("time") or "")
    items = "".join(
        f"<div class='timeline-item'><div class='timeline-dot'></div><div>"
        f"<div style='font-weight:600'>{ev['label']}</div>"
        f"<div style='color:#64748b;font-size:12px'>{ev.get('detail','')} &nbsp;·&nbsp; {_fmt_dt(ev['time'])}</div>"
        f"</div></div>"
        for ev in events
    )
    return f"<h2>Timeline</h2>{items}"


def _notes_block(notes: list) -> str:
    if not notes:
        return "<h2>Notes</h2><p style='color:#94a3b8'>No case notes recorded.</p>"
    blocks = "".join(
        f"<div class='note-block'>"
        f"<div class='note-meta'>{_fmt_dt(n.get('created_at'))} · {n.get('author') or 'Analyst'}</div>"
        f"{n.get('content','')}"
        f"</div>"
        for n in notes
    )
    return f"<h2>Notes</h2>{blocks}"


def _followup_block(edges: list, scans: list, report_type: str) -> str:
    if report_type not in {"summary", "full"}:
        return ""
    items = []
    high_signal = [e for e in edges if e.get("relationship_type", "").upper() in
                   {"FOUND_IN_BREACH", "HAS_VULNERABILITY", "FLAGGED_AS", "HAS_REPUTATION"}]
    if high_signal:
        items.append(f"Review {len(high_signal)} high-signal relationship(s) for validation.")
    if any(s.get("status") in {"partial", "failed", "error"} for s in scans):
        items.append("Review failed or partial scans and rerun missing modules where appropriate.")
    items.append("Validate all findings against source evidence before external distribution.")
    rows = "".join(f"<li>{i}</li>" for i in items)
    return f"<h2>Analyst Follow-Up</h2><ul>{rows}</ul>"


